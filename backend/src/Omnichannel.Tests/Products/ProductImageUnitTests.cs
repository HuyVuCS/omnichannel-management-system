/// <summary>Task 019: what a product image may be, as far as its first bytes can tell.</summary>
public sealed class ProductImageRulesTests
{
    private static readonly byte[] Png = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D];
    private static readonly byte[] Jpeg = [0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01];
    private static readonly byte[] JpegExif = [0xFF, 0xD8, 0xFF, 0xE1, 0x00, 0x10, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00];
    private static readonly byte[] WebP = [.. "RIFF"u8, 0x1A, 0x00, 0x00, 0x00, .. "WEBP"u8];

    [Fact]
    public void Exactly_jpeg_png_and_webp_are_allowed()
    {
        Assert.Equal(["image/jpeg", "image/png", "image/webp"], ProductImageRules.AllowedContentTypes);
        Assert.All(ProductImageRules.AllowedContentTypes, type => Assert.True(ProductImageRules.IsAllowed(type)));
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("image/svg+xml")]
    [InlineData("image/gif")]
    [InlineData("image/jpg")]
    [InlineData("IMAGE/PNG")]
    [InlineData("image/png; charset=utf-8")]
    [InlineData(" image/png")]
    [InlineData("application/octet-stream")]
    [InlineData("text/html")]
    public void Anything_else_is_not_allowed(string? contentType)
    {
        Assert.False(ProductImageRules.IsAllowed(contentType));
    }

    [Fact]
    public void The_first_bytes_of_each_type_are_recognised()
    {
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.Png, Png));
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.Jpeg, Jpeg));
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.Jpeg, JpegExif));
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.WebP, WebP));
        // The shortest input that still carries the whole signature.
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.Png, Png.AsSpan(0, 8)));
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.Jpeg, Jpeg.AsSpan(0, 3)));
        Assert.True(ProductImageRules.StartsLike(ProductImageRules.WebP, WebP.AsSpan(0, ProductImageRules.SignatureLength)));
    }

    [Fact]
    public void Truncated_input_is_not_recognised()
    {
        Assert.False(ProductImageRules.StartsLike(ProductImageRules.Png, Png.AsSpan(0, 7)));
        Assert.False(ProductImageRules.StartsLike(ProductImageRules.Jpeg, Jpeg.AsSpan(0, 2)));
        Assert.False(ProductImageRules.StartsLike(ProductImageRules.WebP, WebP.AsSpan(0, 11)));
        Assert.All(ProductImageRules.AllowedContentTypes, type => Assert.False(ProductImageRules.StartsLike(type, [])));
    }

    public static TheoryData<string, byte[]> Mismatches() => new()
    {
        { ProductImageRules.Png, Jpeg },
        { ProductImageRules.Png, WebP },
        { ProductImageRules.Jpeg, Png },
        { ProductImageRules.Jpeg, WebP },
        { ProductImageRules.WebP, Png },
        { ProductImageRules.WebP, Jpeg },
        // A RIFF container that is not WebP (WAVE), and "WEBP" without RIFF.
        { ProductImageRules.WebP, [.. "RIFF"u8, 0x1A, 0x00, 0x00, 0x00, .. "WAVE"u8] },
        { ProductImageRules.WebP, [.. "JUNK"u8, 0x1A, 0x00, 0x00, 0x00, .. "WEBP"u8] },
        // One byte off.
        { ProductImageRules.Png, [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0B, 0x00, 0x00, 0x00, 0x0D] },
        { ProductImageRules.Jpeg, [0xFF, 0xD8, 0x00, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01] },
        // Text and markup, whatever it is declared as.
        { ProductImageRules.Png, "<svg xmlns=\"http://www.w3.org/2000/svg\">"u8.ToArray() },
        { ProductImageRules.Jpeg, "<!DOCTYPE html><html>"u8.ToArray() },
        { ProductImageRules.WebP, "GIF89a\u0001\u0000\u0001\u0000\u0000\u0000"u8.ToArray() }
    };

    [Theory]
    [MemberData(nameof(Mismatches))]
    public void Content_of_another_kind_than_declared_is_not_recognised(string contentType, byte[] start)
    {
        Assert.False(ProductImageRules.StartsLike(contentType, start));
    }

    [Theory]
    [InlineData("image/gif")]
    [InlineData("image/svg+xml")]
    [InlineData("")]
    public void A_type_that_is_not_allowed_matches_nothing(string contentType)
    {
        Assert.False(ProductImageRules.StartsLike(contentType, Png));
        Assert.False(ProductImageRules.StartsLike(contentType, "GIF89a"u8));
    }
}

/// <summary>Task 019: the key of a product image, generated by the server and accepted back in exactly that form.</summary>
public sealed class ProductImageKeyTests
{
    private static readonly Guid ProductId = Guid.Parse("0199a7c2-5b1e-7c3d-9f00-1234567890ab");
    private const string ObjectId = "0199a7c3-0000-7000-8000-00000000abcd";

    [Fact]
    public void A_new_key_is_products_slash_product_slash_a_uuid_v7_and_belongs_to_its_product()
    {
        var key = ProductImageKey.NewFor(ProductId);

        Assert.Matches("^products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$", key);
        Assert.Equal(Product.MaxImageKeyLength, key.Length);
        Assert.True(ProductImageKey.BelongsTo(key, ProductId));
        Assert.True(ProductImageKey.TryParse(key, out var owner));
        Assert.Equal(ProductId, owner);
        Assert.NotEqual(key, ProductImageKey.NewFor(ProductId));
    }

    [Fact]
    public void A_key_of_another_product_does_not_belong()
    {
        Assert.False(ProductImageKey.BelongsTo(ProductImageKey.NewFor(Guid.NewGuid()), ProductId));
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("products")]
    [InlineData("products/")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId + "/")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId + "/x")]
    [InlineData("products//" + ObjectId)]
    [InlineData("/products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId)]
    [InlineData("Products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId)]
    [InlineData("product/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId)]
    [InlineData("products/0199A7C2-5B1E-7C3D-9F00-1234567890AB/" + ObjectId)]
    [InlineData("products/0199a7c25b1e7c3d9f001234567890ab/" + ObjectId)]
    [InlineData("products/{0199a7c2-5b1e-7c3d-9f00-1234567890ab}/" + ObjectId)]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/not-a-guid")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/0199A7C3-0000-7000-8000-00000000ABCD")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/00000000-0000-0000-0000-000000000000")]
    [InlineData("products/00000000-0000-0000-0000-000000000000/" + ObjectId)]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/../0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId)]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId + " ")]
    [InlineData("products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/" + ObjectId + "?versionId=1")]
    [InlineData("products\\0199a7c2-5b1e-7c3d-9f00-1234567890ab\\" + ObjectId)]
    public void Anything_but_the_generated_form_is_no_key(string? key)
    {
        Assert.False(ProductImageKey.TryParse(key, out _));
        Assert.False(ProductImageKey.BelongsTo(key, ProductId));
    }

    [Fact]
    public void The_generated_form_with_a_fixed_object_id_is_a_key()
    {
        Assert.True(ProductImageKey.BelongsTo($"products/0199a7c2-5b1e-7c3d-9f00-1234567890ab/{ObjectId}", ProductId));
    }
}

/// <summary>Task 019: the image on the product entity is all or nothing.</summary>
public sealed class ProductImageDomainTests
{
    [Fact]
    public void A_new_product_has_no_image_and_set_and_clear_change_all_four_fields_together()
    {
        var product = new Product("SKU-1", "Name", 1m, 0, null);
        Assert.Equal((null, null, null, null), (product.ImageKey, product.ImageContentType, product.ImageSizeBytes, product.ImageUpdatedAt));

        var at = new DateTimeOffset(2026, 10, 4, 1, 2, 3, TimeSpan.Zero);
        var key = ProductImageKey.NewFor(product.ProductId);
        product.SetImage(key, ProductImageRules.Png, 123, at);
        Assert.Equal((key, ProductImageRules.Png, (long?)123, (DateTimeOffset?)at), (product.ImageKey, product.ImageContentType, product.ImageSizeBytes, product.ImageUpdatedAt));

        // An update of the product's own fields leaves the image alone.
        product.Update("Other", 2m, 1, null);
        Assert.Equal(key, product.ImageKey);

        product.ClearImage();
        Assert.Equal((null, null, null, null), (product.ImageKey, product.ImageContentType, product.ImageSizeBytes, product.ImageUpdatedAt));
    }

    [Fact]
    public void An_image_needs_a_key_a_type_and_a_positive_size_that_fit_their_columns()
    {
        var product = new Product("SKU-1", "Name", 1m, 0, null);
        var key = ProductImageKey.NewFor(product.ProductId);
        var at = DateTimeOffset.UtcNow;

        Assert.ThrowsAny<ArgumentException>(() => product.SetImage(" ", ProductImageRules.Png, 1, at));
        Assert.ThrowsAny<ArgumentException>(() => product.SetImage(key, "", 1, at));
        Assert.Throws<ArgumentOutOfRangeException>(() => product.SetImage(key, ProductImageRules.Png, 0, at));
        Assert.Throws<ArgumentOutOfRangeException>(() => product.SetImage(key + "x", ProductImageRules.Png, 1, at));
        Assert.Throws<ArgumentOutOfRangeException>(() => product.SetImage(key, new string('x', Product.MaxImageContentTypeLength + 1), 1, at));
        Assert.Null(product.ImageKey);
    }
}

/// <summary>Task 019: <c>ObjectStorage</c> options - presence and ranges, checked at start-up without connecting.</summary>
public sealed class ObjectStorageOptionsTests
{
    private readonly ObjectStorageOptionsValidator _validator = new();

    private static ObjectStorageOptions Valid() => new()
    {
        ServiceUrl = "http://127.0.0.1:8333",
        BucketName = "omnichannel-dev",
        AccessKeyId = "key-id",
        SecretAccessKey = "secret"
    };

    [Fact]
    public void Defaults_are_as_documented_and_valid_once_endpoint_bucket_and_keys_are_given()
    {
        var options = Valid();

        Assert.True(_validator.Validate(null, options).Succeeded);
        Assert.Equal(
            ("us-east-1", true, TimeSpan.FromMinutes(5), TimeSpan.FromMinutes(15), 5L * 1024 * 1024, TimeSpan.FromSeconds(10)),
            (options.Region, options.ForcePathStyle, options.UploadUrlLifetime, options.DownloadUrlLifetime, options.MaxImageBytes, options.RequestTimeout));
    }

    [Fact]
    public void Nothing_configured_names_every_missing_setting_and_no_value()
    {
        var result = _validator.Validate(null, new ObjectStorageOptions());

        Assert.True(result.Failed);
        Assert.Equal(4, result.Failures!.Count());
        Assert.Contains(result.Failures!, f => f.StartsWith("ObjectStorage:ServiceUrl", StringComparison.Ordinal));
        Assert.Contains(result.Failures!, f => f.StartsWith("ObjectStorage:BucketName", StringComparison.Ordinal));
        Assert.Contains(result.Failures!, f => f.StartsWith("ObjectStorage:AccessKeyId", StringComparison.Ordinal));
        Assert.Contains(result.Failures!, f => f.StartsWith("ObjectStorage:SecretAccessKey", StringComparison.Ordinal));
    }

    public static TheoryData<string, Action<ObjectStorageOptions>> Invalid() => new()
    {
        { "ServiceUrl", o => o.ServiceUrl = "127.0.0.1:8333" },
        { "ServiceUrl", o => o.ServiceUrl = "ftp://storage.example" },
        { "ServiceUrl", o => o.ServiceUrl = "/relative" },
        { "ServiceUrl", o => o.ServiceUrl = "https://key:secret-in-url@storage.example" },
        { "Region", o => o.Region = " " },
        { "BucketName", o => o.BucketName = "" },
        { "AccessKeyId", o => o.AccessKeyId = " " },
        { "SecretAccessKey", o => o.SecretAccessKey = "" },
        { "UploadUrlLifetime", o => o.UploadUrlLifetime = TimeSpan.Zero },
        { "UploadUrlLifetime", o => o.UploadUrlLifetime = TimeSpan.FromDays(7) + TimeSpan.FromSeconds(1) },
        { "DownloadUrlLifetime", o => o.DownloadUrlLifetime = TimeSpan.FromMilliseconds(999) },
        { "DownloadUrlLifetime", o => o.DownloadUrlLifetime = TimeSpan.FromDays(8) },
        { "MaxImageBytes", o => o.MaxImageBytes = 0 },
        { "MaxImageBytes", o => o.MaxImageBytes = ObjectStorageOptionsValidator.MaxImageBytesLimit + 1 },
        { "RequestTimeout", o => o.RequestTimeout = TimeSpan.Zero },
        { "RequestTimeout", o => o.RequestTimeout = TimeSpan.FromMinutes(3) }
    };

    [Theory]
    [MemberData(nameof(Invalid))]
    public void One_invalid_setting_is_one_failure_that_names_it(string setting, Action<ObjectStorageOptions> change)
    {
        var options = Valid();
        change(options);

        var result = _validator.Validate(null, options);

        var failure = Assert.Single(result.Failures!);
        Assert.StartsWith($"ObjectStorage:{setting} ", failure, StringComparison.Ordinal);
        // A message never repeats a configured value (it could be a credential).
        Assert.DoesNotContain("secret-in-url", failure);
    }

    [Fact]
    public void The_limits_themselves_are_valid()
    {
        var options = Valid();
        options.ServiceUrl = "https://s3.provider.example";
        options.UploadUrlLifetime = TimeSpan.FromSeconds(1);
        options.DownloadUrlLifetime = TimeSpan.FromDays(7);
        options.MaxImageBytes = ObjectStorageOptionsValidator.MaxImageBytesLimit;
        options.RequestTimeout = TimeSpan.FromMinutes(2);

        Assert.True(_validator.Validate(null, options).Succeeded);
    }
}
